function formatWhen(iso, lang, timeKnown) {
	const date = new Date(iso);
	const locale = lang === "es" ? "es-MX" : "en-GB";
	return {
		day: new Intl.DateTimeFormat(locale, {
			timeZone: "America/Merida",
			weekday: "short",
			day: "2-digit",
			month: "short",
			year: "numeric"
		}).format(date),
		time: timeKnown ? new Intl.DateTimeFormat(locale, {
			timeZone: "America/Merida",
			hour: "2-digit",
			minute: "2-digit",
			hour12: false
		}).format(date) : null,
		stamp: new Intl.DateTimeFormat("en-GB", {
			timeZone: "America/Merida",
			day: "2-digit",
			month: "2-digit",
			year: "2-digit"
		}).format(date).replaceAll("/", ".")
	};
}
